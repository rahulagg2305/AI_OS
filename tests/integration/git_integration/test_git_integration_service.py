def test_push_to_a_protected_branch_is_refused_and_the_remote_receives_nothing(
    database_url: str,
) -> None:
    async def _run() -> None:
        engine: AsyncEngine = build_engine(database_url)
        try:
            with (
                tempfile.TemporaryDirectory(prefix="aios-git-workspace-") as workdir_str,
                tempfile.TemporaryDirectory(prefix="aios-git-remote-") as remote_str,
            ):
                workspace = Path(workdir_str)
                remote = Path(remote_str)
                await _git(["init", "--bare", str(remote)])
                (workspace / "f.txt").write_text("x")

                audit_log = SqlAuditLogWriter(engine)
                service = GitIntegrationService(
                    sandbox=LocalSubprocessSandbox(),
                    audit_log=audit_log,
                    push_policy=GitPushPolicy(protected_branches=frozenset({"main"})),
                    author_name="AI_OS Bot",
                    author_email="bot@ai-os.internal",
                )
                await service.commit(
                    workspace=workspace, message="c1", actor_id="a", actor_type="agent"
                )
                # The real default branch this repo's own git version
                # creates ("main" or "master") — force it to "main" so
                # this test exercises the real protected-branch path
                # regardless of the runner's own git default.
                await _git(["branch", "-M", "main"], cwd=workspace)

                with pytest.raises(ProtectedBranchPushRefusedError):
                    await service.push(
                        workspace=workspace,
                        branch="main",
                        remote_url=str(remote),
                        actor_id="agent-build",
                        actor_type="agent",
                    )

                # The remote is still genuinely empty — refused before
                # any subprocess touched it, not merely reported as an
                # error after a real push attempt.
                assert await _remote_refs(remote) == ""

                rows = await audit_log.list_all()
                record = next(r for r in rows if r.event_type == "git.push.denied")
                assert record.outcome == AuditOutcome.DENIED
                assert record.detail["reason"] == "protected_branch"
        finally:
            await engine.dispose()

    asyncio.run(_run())


def test_push_with_a_real_credential_resolves_it_and_never_leaks_it(database_url: str) -> None:
    async def _run() -> None:
        engine: AsyncEngine = build_engine(database_url)
        try:
            with (
                tempfile.TemporaryDirectory(prefix="aios-git-workspace-") as workdir_str,
                tempfile.TemporaryDirectory(prefix="aios-git-remote-") as remote_str,
            ):
                workspace = Path(workdir_str)
                remote = Path(remote_str)
                await _git(["init", "--bare", str(remote)])
                (workspace / "f.txt").write_text("x")

                audit_log = SqlAuditLogWriter(engine)
                provider = EnvSecretProvider(env={"AIOS_SECRET_GIT_TOKEN": _SECRET_TOKEN})
                broker = AccessBroker(provider=provider, audit_log=audit_log)
                service = GitIntegrationService(
                    sandbox=LocalSubprocessSandbox(),
                    audit_log=audit_log,
                    push_policy=GitPushPolicy(protected_branches=frozenset({"main"})),
                    author_name="AI_OS Bot",
                    author_email="bot@ai-os.internal",
                    secret_broker=broker,
                )
                await service.commit(
                    workspace=workspace, message="c1", actor_id="a", actor_type="agent"
                )
                await service.create_branch(
                    workspace=workspace,
                    branch_name="feature/with-credential",
                    actor_id="a",
                    actor_type="agent",
                )

                await service.push(
                    workspace=workspace,
                    branch="feature/with-credential",
                    remote_url=str(remote),
                    credential_reference="secret://env/git-token",
                    security_context=_admin_context(),
                    actor_id="agent-build",
                    actor_type="agent",
                )

                # The real, separate remote genuinely received the push
                # — the credential mechanism ran for real and did not
                # block the operation.
                assert "refs/heads/feature/with-credential" in await _remote_refs(remote)

                # The one property that matters most: the real secret
                # value is never anywhere in the real audit trail — not
                # in this service's own rows, and not in the
                # already-proven AccessBroker's own resolution row
                # either (both write to the same table here).
                rows = await audit_log.list_all()
                assert any(r.event_type == "secret.access.allowed" for r in rows)
                assert any(r.event_type == "git.push.succeeded" for r in rows)
                for record in rows:
                    assert _SECRET_TOKEN not in str(record.detail)
        finally:
            await engine.dispose()

    asyncio.run(_run())
