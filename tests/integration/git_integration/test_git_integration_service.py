def _git_binary() -> str:
    found = shutil.which("git")
    if found is None:
        pytest.skip("git is not available on PATH")
    return found


async def _git(args: Sequence[str], *, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    """Runs the real, resolved ``git`` binary off the event loop thread
    (this file's own test-driver calls, never the service under test —
    that always goes through the real `LocalSubprocessSandbox`)."""
    return await asyncio.to_thread(
        subprocess.run,
        [_git_binary(), *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        check=True,
    )


