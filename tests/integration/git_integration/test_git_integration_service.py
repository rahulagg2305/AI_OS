def _admin_context() -> SecurityContext:
    return SecurityContext(
        principal=Principal(
            principal_id="admin-1", principal_type=PrincipalType.USER, roles=frozenset({"admin"})
        ),
        permissions=frozenset({SECRET_ACCESS}),
    )


async def _remote_refs(remote_path: Path) -> str:
    result = await _git(["ls-remote", str(remote_path)])
    return result.stdout


def test_commit_creates_a_real_commit_and_is_audited(database_url: str) -> None:
    async def _run() -> None:
        engine: AsyncEngine = build_engine(database_url)
        try:
            with tempfile.TemporaryDirectory(prefix="aios-git-workspace-") as workdir_str:
                workspace = Path(workdir_str)
                (workspace / "generated.txt").write_text("generated by an agent")

                audit_log = SqlAuditLogWriter(engine)
                service = GitIntegrationService(
                    sandbox=LocalSubprocessSandbox(),
                    audit_log=audit_log,
                    push_policy=GitPushPolicy(protected_branches=frozenset({"main"})),
                    author_name="AI_OS Bot",
                    author_email="bot@ai-os.internal",
                )

                result = await service.commit(
                    workspace=workspace,
                    message="real generated work",
                    actor_id="agent-build",
                    actor_type="agent",
                )

                # Read the real repository back directly — not trusting
                # the service's own return value alone.
                log = await _git(["log", "-1", "--format=%H %an %ae %s"], cwd=workspace)
                assert log.stdout.startswith(result.commit_sha)
                assert "AI_OS Bot bot@ai-os.internal real generated work" in log.stdout

                rows = await audit_log.list_all()
                record = next(r for r in rows if r.event_type == "git.commit.succeeded")
                assert record.principal_id == "agent-build"
                assert record.outcome == AuditOutcome.SUCCESS
                assert record.detail["commit_sha"] == result.commit_sha
        finally:
            await engine.dispose()

    asyncio.run(_run())


